import { createHmac, timingSafeEqual } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import type { FileStorage, StoredHead, UploadTarget } from '../domain/ports/file-storage.ts';

/**
 * Local adapter of the `FileStorage` port: a directory on disk (dev and e2e, spec §1.3). The
 * production adapter is R2 (`r2-file-storage.ts`); both speak the same port, so the domain and
 * the application layer never learn which one is in use.
 *
 * The "presigned" URL of this adapter points at the app's own route (`/pliki/<key>`) and carries
 * an HMAC signature over key, type, size and expiry — the browser may upload only that exact
 * object, only with that type and size, and only before the expiry.
 */
export interface LocalFileStorageOptions {
  /** Directory the objects live in. */
  readonly root: string;
  /** HMAC key of the upload URLs. */
  readonly signingSecret: string;
  /**
   * Public origin of the app. Optional: without it the URLs are relative (`/pliki/<key>`), which
   * the browser resolves against the page origin — handy in dev and e2e on any port.
   */
  readonly publicUrl?: string;
  /** Clock in seconds; injectable for the contract test. */
  readonly now?: () => number;
}

/** Key → path segment: the key is generated by the server, but a traversal must be impossible. */
const encodeKey = (key: string): string =>
  key
    .split('/')
    .map((segment) => encodeURIComponent(segment))
    .join('/');

/** The signed payload: what the browser may upload, how big, and until when. */
const payloadOf = (params: {
  key: string;
  contentType: string;
  size: number;
  expiresAt: number;
}): string => `${params.key}\n${params.contentType}\n${params.size}\n${params.expiresAt}`;

const sign = (secret: string, payload: string): string =>
  createHmac('sha256', secret).update(payload).digest('hex');

export interface LocalUploadRequest {
  readonly key: string;
  readonly contentType: string;
  readonly size: number;
  readonly expiresAt: number;
  readonly signature: string;
  readonly body: Uint8Array;
}

export class LocalFileStorage implements FileStorage {
  readonly #root: string;
  readonly #secret: string;
  readonly #publicUrl: string | undefined;
  readonly #now: () => number;

  constructor(options: LocalFileStorageOptions) {
    this.#root = resolve(options.root);
    this.#secret = options.signingSecret;
    this.#publicUrl = options.publicUrl?.replace(/\/+$/, '');
    this.#now = options.now ?? (() => Math.floor(Date.now() / 1000));
  }

  /** Absolute path of a key; keys escaping the root are rejected. */
  #pathOf(key: string): string {
    const path = resolve(this.#root, key);
    if (path !== this.#root && !path.startsWith(this.#root + sep)) {
      throw new Error(`Invalid storage key: ${key}`);
    }
    return path;
  }

  createUploadUrl(params: {
    key: string;
    contentType: string;
    size: number;
    expiresInSeconds: number;
  }): Promise<UploadTarget> {
    const expiresAt = this.#now() + params.expiresInSeconds;
    const signature = sign(
      this.#secret,
      payloadOf({ key: params.key, contentType: params.contentType, size: params.size, expiresAt }),
    );
    const query = new URLSearchParams({
      contentType: params.contentType,
      size: String(params.size),
      expires: String(expiresAt),
      signature,
    });
    const path = `/pliki/${encodeKey(params.key)}?${query.toString()}`;
    return Promise.resolve({
      url: this.#publicUrl ? `${this.#publicUrl}${path}` : path,
      method: 'PUT',
      headers: { 'content-type': params.contentType },
    });
  }

  readHead(key: string, bytes: number): Promise<StoredHead | null> {
    return this.#read(key).then((content) =>
      content === null
        ? null
        : { bytes: content.bytes.slice(0, bytes), size: content.bytes.length },
    );
  }

  async delete(key: string): Promise<void> {
    await rm(this.#pathOf(key), { force: true });
  }

  publicUrl(key: string): string {
    const path = `/pliki/${encodeKey(key)}`;
    return this.#publicUrl ? `${this.#publicUrl}${path}` : path;
  }

  /** Reads the whole object — the local route serves it to the browser. */
  async readObject(
    key: string,
  ): Promise<{ bytes: Uint8Array; contentType: string } | null> {
    const content = await this.#read(key);
    if (content === null) return null;
    return { bytes: content.bytes, contentType: guessContentType(key) };
  }

  /**
   * Accepts an upload of the local route: the signature must match the key, type, size and
   * expiry, and the body must have exactly the declared size. Anything else is refused.
   */
  async acceptUpload(request: LocalUploadRequest): Promise<boolean> {
    if (request.expiresAt < this.#now()) return false;
    if (request.body.length !== request.size) return false;
    const expected = sign(
      this.#secret,
      payloadOf({
        key: request.key,
        contentType: request.contentType,
        size: request.size,
        expiresAt: request.expiresAt,
      }),
    );
    if (!sameSignature(expected, request.signature)) return false;
    const path = this.#pathOf(request.key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, request.body);
    return true;
  }

  async #read(key: string): Promise<{ bytes: Uint8Array } | null> {
    try {
      const bytes = await readFile(this.#pathOf(key));
      return { bytes: new Uint8Array(bytes) };
    } catch {
      return null;
    }
  }
}

/** Constant-time comparison of two hex signatures. */
const sameSignature = (expected: string, given: string): boolean => {
  if (given.length !== expected.length) return false;
  try {
    return timingSafeEqual(Buffer.from(expected, 'hex'), Buffer.from(given, 'hex'));
  } catch {
    return false;
  }
};

/** The type is part of the signed payload, but the route needs it to answer with a content type. */
const CONTENT_TYPES: Record<string, string> = {
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
  png: 'image/png',
  webp: 'image/webp',
};

const guessContentType = (key: string): string => {
  const extension = key.split('.').pop()?.toLowerCase() ?? '';
  return CONTENT_TYPES[extension] ?? 'application/octet-stream';
};
