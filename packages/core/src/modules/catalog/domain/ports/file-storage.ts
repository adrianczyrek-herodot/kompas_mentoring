/** Where and how the browser sends the file itself (presigned, spec "Bezpieczeństwo"). */
export interface UploadTarget {
  readonly url: string;
  readonly method: 'PUT';
  /** Headers the browser must send unchanged — they are part of the signature. */
  readonly headers: Readonly<Record<string, string>>;
}

export interface StoredHead {
  /** The first bytes of the object (enough to read image dimensions). */
  readonly bytes: Uint8Array;
  /** Full object size in bytes. */
  readonly size: number;
}

/**
 * Port: object storage for user files (spec §1.3) — R2 in the EU jurisdiction in production, a
 * directory on disk in dev/e2e, an in-memory fake in tests. Keys are always generated by the server.
 */
export interface FileStorage {
  /** Presigned direct upload of exactly `size` bytes of `contentType`, valid for `expiresInSeconds`. */
  createUploadUrl(params: {
    key: string;
    contentType: string;
    size: number;
    expiresInSeconds: number;
  }): Promise<UploadTarget>;
  /** First `bytes` bytes of the object, or `null` when nothing was uploaded under the key. */
  readHead(key: string, bytes: number): Promise<StoredHead | null>;
  /** Removes the object; removing a missing object is not an error. */
  delete(key: string): Promise<void>;
  /** URL under which the browser displays the file. */
  publicUrl(key: string): string;
}
