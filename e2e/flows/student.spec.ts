import { expect, test } from "@playwright/test";
import { asRole, expectToast, go, open } from "../support";

test("F1: gość → termin → rejestracja → płatność z KOMPAS10 → potwierdzenie", async ({ page }) => {
  await open(page, "/mentorzy/m1");
  await page.click('a:has-text("Zarezerwuj sesję próbną")');
  await expect(page).toHaveURL(/\/rezerwacja\/m1$/);
  await expect(page.locator("[data-continue]")).toBeDisabled();
  await page.click("[data-sim409]");
  await expectToast(page, "Najpierw wybierz termin");
  const slot = page.locator("[data-slot]:not([disabled])").first();
  const iso = await slot.getAttribute("data-slot");
  await slot.click();
  await expect(page.locator("[data-sel-label]")).not.toHaveText("—");
  await page.click("[data-sim409]");
  await expect(page.locator(`[data-slot="${iso}"]`)).toBeDisabled();
  await page.locator("[data-slot]:not([disabled])").first().click();
  await page.click("[data-continue]");
  await expect(page).toHaveURL(/\/rejestracja$/);
  await expect(page.locator("main")).toContainText("Twój wybrany termin jest zachowany");
  await page.fill("#f-name", "Ada");
  await page.fill("#f-email", "ada@firma.pl");
  await page.fill("#f-password", "bardzotajne1");
  await page.check("input[name=terms]");
  await page.click("form button[type=submit]");
  await expect(page).toHaveURL(/\/rezerwacja\/m1\/platnosc$/);
  await expect(page.locator("[data-total]")).toContainText("52");
  await page.fill("#f-promo", "ZLY");
  await page.click("[data-promo]");
  await expect(page.locator("main")).toContainText("Ten kod jest nieprawidłowy lub wygasł.");
  await page.fill("#f-promo", "kompas10");
  await page.click("[data-promo]");
  await expect(page.locator("[data-total]")).toContainText("47");
  await page.fill("#f-goal", "krótko");
  await page.fill("#f-card", "1234");
  await page.click("form button[type=submit]");
  await expect(page.locator("main")).toContainText("Podaj 16 cyfr numeru karty.");
  await expect(page.locator("main")).toContainText("Format MM/RR.");
  await page.fill("#f-goal", "Chcę przejrzeć projekt portfolio w React i plan nauki.");
  await page.fill("#f-card", "4242 4242 4242 4242");
  await page.fill("#f-exp", "12/28");
  await page.fill("#f-cvc", "123");
  await page.check("input[name=simDecline]");
  await page.click("form button[type=submit]");
  await expectToast(page, "Płatność odrzucona");
  await expect(page).toHaveURL(/\/platnosc$/);
  await page.uncheck("input[name=simDecline]");
  await page.click("form button[type=submit]");
  await expect(page).toHaveURL(/\/potwierdzenie\/s101$/);
  await expect(page.locator("main")).toContainText("potwierdzi termin w ciągu 24 h");
  await go(page, "/sesje");
  await expect(page.locator("main")).toContainText("Nadchodzące (1)");
});

