test("U8–U9, S2–S3: plan, saldo, postępy, powiadomienia, konto", async ({ page }) => {
  await open(page, "/");
  await asRole(page, "student");
  await go(page, "/plany");
  await page.click("[data-pause]");
  await expect(page.locator("[data-pause]")).toHaveText("Wznów");
  await page.locator("[data-transfer]").first().click();
  await expect(page.getByRole("dialog")).toContainText(/→ \d+ u /);
  await page.click('[role="dialog"] [data-ok]');
  await expectToast(page, "Saldo przeniesione");
  await page.click("[data-cancel-sub]");
  await page.click('[role="dialog"] [data-ok]');
  await expect(page.locator("main")).toContainText("Nie masz aktywnego planu");
  await go(page, "/postepy");
  const bar = page.getByRole("progressbar");
  const before = await bar.getAttribute("aria-valuenow");
  await page.locator("main input[type=checkbox]").nth(1).check();
  await expect(bar).not.toHaveAttribute("aria-valuenow", before ?? "");
  await go(page, "/powiadomienia");
  await page.click("[data-read]");
  await expect(page.locator("[data-read]")).toHaveCount(0);
  await expect(page.locator('header [aria-label="Powiadomienia"] span')).toHaveCount(0);
  await go(page, "/konto");
  await page.fill("#f-email", "zly");
  await page.click("main form button[type=submit]");
  await expect(page.locator("main")).toContainText("Podaj poprawny adres e-mail.");
});

test("S1: wiadomości — logowanie z profilu, ostrzeżenie, nieudane wysłanie", async ({ page }) => {
  await open(page, "/mentorzy/m3");
  await page.click('a:has-text("Napisz wiadomość")');
  await expect(page).toHaveURL(/\/logowanie$/);
  await page.click("[data-social]");
  // Ewa Sadowska (m3) ma już wątek t2 w danych demo.
  await expect(page).toHaveURL(/\/wiadomosci\/t2$/);
  await go(page, "/mentorzy/m4");
  await page.click('a:has-text("Napisz wiadomość")');
  await expect(page).toHaveURL(/\/wiadomosci\/t-m4$/);
  await page.fill("textarea[name=text]", "Mój numer: 600 700 800");
  await expect(page.locator("[data-warn]")).toBeVisible();
  await page.press("textarea[name=text]", "Enter");
  await expect(page.locator("[data-body]")).toContainText("600 700 800");
  await page.fill("textarea[name=text]", "tu jest błąd");
  await page.press("textarea[name=text]", "Enter");
  await expect(page.locator("[data-body]")).toContainText("Nie wysłano · Ponów");
  await page.click("[data-resend]");
  await expect(page.locator("[data-body]")).not.toContainText("Nie wysłano");
  await page.press("textarea[name=text]", "Enter");
  await expect(page.locator("main")).toContainText("Wiadomość nie może być pusta.");
});

